'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const w=JSON.parse(fs.readFileSync('backend/v2/communication/candidate-workflows/comm-api-service.json','utf8'));
const node=n=>w.nodes.find(x=>x.name===n);
const history=node('Read Page'),changes=node('Read Changes Page'),split=node('History Page');
assert.ok(history&&changes&&split,'explicit history/change pagination nodes required');
assert.equal(typeof history.parameters.filters,'object');
assert.equal(typeof changes.parameters.filters,'object');
assert.equal(history.parameters.orderByDirection,'DESC');
assert.equal(changes.parameters.orderByDirection,'ASC');
assert.ok(history.parameters.filters.conditions.some(c=>c.keyName==='kind'&&c.keyValue==='DELIVERY'));
assert.ok(history.parameters.filters.conditions.some(c=>c.keyName==='scope_id'));
assert.ok(history.parameters.filters.conditions.some(c=>c.keyName==='id'&&c.condition==='lt'&&String(c.keyValue).includes('2147483647')));
assert.ok(changes.parameters.filters.conditions.some(c=>c.keyName==='kind'&&c.keyValue==='EVENT'));
assert.ok(changes.parameters.filters.conditions.some(c=>c.keyName==='scope_id'));
assert.ok(changes.parameters.filters.conditions.some(c=>c.keyName==='revision'&&c.condition==='gt'));
assert.ok(changes.parameters.filters.conditions.some(c=>c.keyName==='revision'&&c.condition==='lte'));
assert.ok(changes.parameters.filters.conditions.some(c=>c.keyName==='id'&&c.condition==='gt'));
assert.equal(w.connections['Needs Page'].main[0][0].node,'History Page');
assert.equal(w.connections['History Page'].main[0][0].node,'Read Page');
assert.equal(w.connections['History Page'].main[1][0].node,'Read Changes Page');
for(const n of [history,changes]){assert.equal(n.parameters.returnAll,false);assert.equal(n.alwaysOutputData,true);assert.equal(n.executeOnce,true);assert.ok(String(n.parameters.limit).includes('limit + 1'));}
console.log('Communication pagination graph PASS: explicit scoped Data Table filters for history and changes.');
